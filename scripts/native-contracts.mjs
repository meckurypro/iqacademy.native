#!/usr/bin/env node
// scripts/native-contracts.mjs — what backend does the NATIVE app call? (the web side is scripts/gen-contracts.mjs)
//   node scripts/native-contracts.mjs            print a compact list:  rpc:<name>(<arg keys>) | table:<name> | bucket:<name> | fn:<name>
//   node scripts/native-contracts.mjs --json     the same as JSON (feed it to the live-database comparison in port/sql/native-contracts-check.sql)
// Static scan, so it can miss names built at run time; it errs on the side of listing too much.
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : /\.tsx?$/.test(p) ? [p] : []; });
const files = walk(join(root, "src")).filter((f) => !/\.generated\.|src\/shared\/web\/|src\/dev\//.test(f));

const rpcs = new Map(), tables = new Set(), buckets = new Set(), fns = new Set();
// keys of the first `{ ... }` after a call, at nesting depth 1 only (so nested objects don't leak keys)
const keysOf = (src, from) => {
  const lead = /^\s*,\s*\{/.exec(src.slice(from, from + 40)); if (!lead) return null;
  const open = from + lead[0].length - 1;
  let depth = 0, q = null, keys = [], i = open;
  for (; i < src.length; i++) {
    const c = src[i];
    if (q) { if (c === "\\") i++; else if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === "`") { q = c; continue; }
    if ("{[(".includes(c)) { depth++; continue; }
    if ("}])".includes(c)) { depth--; if (depth === 0) break; continue; }
    if (depth === 1) {
      const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?::|,|\})/.exec(src.slice(i, i + 80));
      if (m && (i === open + 1 || /[,{]\s*$/.test(src.slice(Math.max(open, i - 12), i)))) { keys.push(m[1]); i += m[0].length - 1; if (src[i] === "}") break; }
    }
  }
  return keys;
};
for (const f of files) {
  const src = readFileSync(f, "utf8");
  // .rpc("x", {..})  mutateRpc("x", {..})  useRpc("x", {..})  mutateRpc<T>("x", ...)  ok(await sb.rpc("x"
  for (const m of src.matchAll(/(?:\.rpc|mutateRpc|useRpc|callRpc)(?:<[^>(]*>)?\(\s*"([a-z_0-9]+)"/g)) {
    const after = m.index + m[0].length;
    const k = keysOf(src, after) ?? [];
    const e = rpcs.get(m[1]) ?? { keys: new Set(), files: new Set() };
    (k ?? []).forEach((x) => e.keys.add(x)); e.files.add(f.replace(root + "/src/", "")); rpcs.set(m[1], e);
  }
  for (const m of src.matchAll(/\.from\("([a-z_0-9]+)"\)(?!\.(?:upload|download|remove|createSignedUrl|getPublicUrl|list))/g)) tables.add(m[1]);
  for (const m of src.matchAll(/storage\.from\("([a-z-]+)"\)/g)) buckets.add(m[1]);
  for (const m of src.matchAll(/(?:invokeFunction|functions\.invoke)(?:<[^>(]*>)?\(\s*"([a-z-]+)"/g)) fns.add(m[1]);
  for (const m of src.matchAll(/(?:BUCKET|bucket)\s*[:=]\s*"([a-z-]+)"/g)) buckets.add(m[1]);
}
const out = { rpcs: [...rpcs].sort(([a], [b]) => a.localeCompare(b)).map(([name, e]) => ({ name, keys: [...e.keys].sort(), files: [...e.files].sort() })), tables: [...tables].sort(), buckets: [...buckets].sort(), functions: [...fns].sort() };
if (process.argv.includes("--sql")) {
  // A read-only comparison with the live database. Run it through the Supabase connector's execute_sql (SELECT only).
  // "unknown_keys" = argument names the database function does not have; "missing_required" = required arguments this call never passes
  // (checked only when the call has a literal argument object); "dynamic_args" = calls whose arguments are built at run time (read by eye).
  const list = out.rpcs.map((r) => `${r.name}|${r.keys.join(",")}`).join("\n");
  const arr = (a) => `array[${a.map((x) => `'${x}'`).join(",")}]::text[]`;
  console.log(`-- generated by scripts/native-contracts.mjs --sql  (read-only)
with native as (
  select split_part(l, '|', 1) as name, string_to_array(nullif(split_part(l, '|', 2), ''), ',') as keys
  from unnest(string_to_array($list$
${list}
$list$, E'\n')) l where l <> ''),
db as (
  select p.proname as name, p.proargnames as names, p.proargnames[1:p.pronargs - p.pronargdefaults] as required
  from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prokind = 'f'),
chk as (
  select n.name, n.keys,
    exists (select 1 from db where db.name = n.name) as in_db,
    (select coalesce(array_agg(k), '{}') from unnest(coalesce(n.keys, '{}')) k
       where not exists (select 1 from db where db.name = n.name and k = any (db.names))) as unknown_keys,
    (select coalesce(array_agg(distinct r), '{}') from db, unnest(coalesce(db.required, '{}')) r
       where db.name = n.name and n.keys is not null and cardinality(n.keys) > 0 and not (r = any (n.keys))) as missing_required,
    (select coalesce(array_agg(distinct r), '{}') from db, unnest(coalesce(db.required, '{}')) r
       where db.name = n.name and (n.keys is null or cardinality(n.keys) = 0)) as dynamic_args
  from native n)
select json_build_object(
  'rpc_count', (select count(*) from native),
  'rpc_problems', (select json_agg(json_build_object('rpc', name, 'in_db', in_db, 'unknown_keys', unknown_keys, 'missing_required', missing_required)) from chk where not in_db or cardinality(unknown_keys) > 0 or cardinality(missing_required) > 0),
  'dynamic_args_to_check_by_eye', (select json_agg(json_build_object('rpc', name, 'required', dynamic_args)) from chk where cardinality(dynamic_args) > 0),
  'missing_tables', (select json_agg(t) from unnest(${arr(out.tables)}) t where to_regclass('public.' || t) is null),
  'missing_buckets', (select json_agg(b) from unnest(${arr(out.buckets)}) b where not exists (select 1 from storage.buckets where id = b))
) as native_contract_check;`);
} else if (process.argv.includes("--json")) console.log(JSON.stringify(out));
else { console.log(`native calls ${out.rpcs.length} RPCs, ${out.tables.length} tables/views, ${out.buckets.length} buckets, ${out.functions.length} edge functions\n`); for (const r of out.rpcs) console.log(`rpc:${r.name}(${r.keys.join(",")})`); console.log("\ntables:", out.tables.join(", ")); console.log("buckets:", out.buckets.join(", ")); console.log("functions:", out.functions.join(", ")); }
